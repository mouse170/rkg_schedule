// Helper to find girl by name or alias
export function findGirlByName(name: string): GirlProfile | undefined {
  const trimmed = name.trim();
  // exact match
  let found = OFFICIAL_GIRLS.find(g => g.name === trimmed);
  if (found) return found;

  // alias handling
  if (trimmed === '珈妤') {
    return OFFICIAL_GIRLS.find(g => g.name === '沈珈妤');
  }
  if (trimmed.includes('曲羿') || trimmed.includes('曲曲')) {
    return OFFICIAL_GIRLS.find(g => g.name === '曲曲');
  }
  if (trimmed.includes('梔梔') || trimmed.includes('崔荷潾')) {
    return OFFICIAL_GIRLS.find(g => g.name === '崔荷潾');
  }

  // partial match
  return OFFICIAL_GIRLS.find(g => g.name.includes(trimmed) || trimmed.includes(g.name));
}
